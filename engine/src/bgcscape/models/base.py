"""Shared base class, mixins, and cross-cutting enums for the BGC-scape data model.

Every scientific entity in BGC-scape must be traceable to a `Source` and
carry an explicit `EvidenceLevel`. This is the mechanical enforcement of the
project's epistemic-rigor principle: BGC-scape never presents a computed or
predicted fact with the same confidence as a curated, experimentally-verified
one. See ARCHITECTURE.md → "Provenance is structural, not conventional".
"""
from __future__ import annotations

import enum
import uuid
from datetime import datetime, timezone

from sqlalchemy import DateTime, ForeignKey
from sqlalchemy import Enum as SAEnum
from sqlalchemy.orm import DeclarativeBase, Mapped, declared_attr, mapped_column


class Base(DeclarativeBase):
    """Declarative base for every BGC-scape ORM model."""


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


class TimestampMixin:
    """Adds created_at / updated_at bookkeeping columns."""

    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_utcnow, nullable=False)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=_utcnow, onupdate=_utcnow, nullable=False
    )


class EvidenceLevel(str, enum.Enum):
    """Epistemic status of a fact stored in BGC-scape.

    OBSERVED_CURATED  Directly reported by a canonical reference (e.g. a MIBiG
                       experimentally-characterized BGC-to-compound link, a
                       GTDB type-strain taxonomy assignment). Highest
                       confidence.
    COMPUTED           Deterministically derived by a defined, versioned
                       pipeline from other stored data (e.g. a BiG-SCAPE
                       family assignment, an IQ-TREE phylogenetic placement).
                       Reproducible given the same inputs and parameters, but
                       not independently observed.
    PREDICTED          Output of a heuristic/probabilistic tool carrying
                       inherent uncertainty (e.g. an antiSMASH BGC
                       boundary/class call, a GTDB-Tk placement of a MAG).
                       Treated as a hypothesis pending corroboration.
    HYPOTHESIZED       A hypothesis generated by BGC-scape itself or a user
                       (e.g. a novelty flag, a manual annotation). Lowest
                       confidence, always presented as exploratory rather
                       than factual.
    """

    OBSERVED_CURATED = "observed_curated"
    COMPUTED = "computed"
    PREDICTED = "predicted"
    HYPOTHESIZED = "hypothesized"


class ProvenanceMixin:
    """Attaches mandatory source + evidence-level tracking to an entity.

    Nothing in BGC-scape's core data model is allowed to exist without a
    traceable origin: `source_id` and `evidence_level` are both
    `nullable=False`. Inserting a row without them is a database-level
    IntegrityError, not a convention someone can forget to follow.
    """

    @declared_attr
    def source_id(cls) -> Mapped[uuid.UUID]:  # noqa: N805 - SQLAlchemy declared_attr convention
        return mapped_column(ForeignKey("source.id"), nullable=False, index=True)

    @declared_attr
    def evidence_level(cls) -> Mapped[EvidenceLevel]:  # noqa: N805
        # create_constraint=True is NOT the default for native_enum=False in
        # SQLAlchemy 2.0 (it defaults to no DB-level constraint at all,
        # relying only on validate_strings' Python-side check) — passing it
        # explicitly is what actually gives this column a real CHECK
        # constraint, matching ARCHITECTURE.md's "VARCHAR + CHECK" claim.
        # values_callable is equally important and easy to miss: SQLAlchemy
        # defaults to storing a (str, Enum)'s *member name*
        # ("OBSERVED_CURATED"), not the lowercase `.value` the enum was
        # deliberately defined with ("observed_curated") — without this,
        # the raw DB contents silently diverge from what every JSON
        # schema/API response actually emits (Pydantic serializes `.value`).
        # Named per-table (via declared_attr) since this mixin is shared
        # across many tables and constraint names should be unambiguous.
        return mapped_column(
            SAEnum(
                EvidenceLevel,
                native_enum=False,
                length=32,
                validate_strings=True,
                create_constraint=True,
                values_callable=lambda enum_cls: [member.value for member in enum_cls],
                name=f"ck_{cls.__tablename__}_evidence_level_valid",
            ),
            nullable=False,
        )
