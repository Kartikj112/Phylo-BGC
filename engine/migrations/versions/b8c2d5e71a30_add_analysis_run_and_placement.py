def _backfill_placements() -> None:
    """Lift every placement out of `BGC.raw_annotation` into the new table.

    Reads the JSON in Python rather than with a dialect-specific JSON
    operator, because this has to run identically on SQLite and Postgres and
    the two spell that operator differently. The corpus this runs against is
    thousands of rows, not millions, so a single pass is the right cost.

    Rows whose recorded method is not in the vocabulary are skipped rather
    than coerced: the old column was free text, and inventing a method for a
    value nobody defined would be exactly the kind of fabrication the new
    CHECK constraint exists to prevent. They keep their JSON and are
    reported by the count below.
    """
    bind = op.get_bind()
    rows = bind.execute(
        sa.text(
            "SELECT b.id, b.genome_id, b.source_id, b.evidence_level, b.raw_annotation "
            "FROM bgc b WHERE b.raw_annotation IS NOT NULL"
        )
    ).fetchall()

    now = datetime.now(timezone.utc)
    inserts = []
    unknown_methods: set[str] = set()
    for bgc_id, genome_id, source_id, evidence_level, raw in rows:
        if isinstance(raw, (str, bytes)):
            try:
                raw = json.loads(raw)
            except (ValueError, TypeError):
                continue
        if not isinstance(raw, dict):
            continue
        placement = raw.get(_PLACEMENT_KEY)
        if not isinstance(placement, dict):
            continue
        method = str(placement.get("method") or "").strip()
        if method not in _CONFIDENCE_BY_METHOD:
            if method:
                unknown_methods.add(method)
            continue
        inserts.append(
            {
                "id": uuid.uuid4(),
                "bgc_id": _as_uuid(bgc_id),
                "representative_genome_id": _as_uuid(genome_id),
                "method": method,
                "confidence": _CONFIDENCE_BY_METHOD[method],
                "gtdb_accession": placement.get("gtdb_accession"),
                "caveat": _CAVEAT_BY_METHOD[method],
                "created_at": now,
                "updated_at": now,
                "source_id": _as_uuid(source_id),
                # The placement is an inference Phylo-BGC computed from a
                # taxid/name mapping — not something MIBiG curated. It
                # inherits the cluster's source (MIBiG supplied the organism)
                # but never its OBSERVED_CURATED level: the curation is
                # MIBiG's, the placement is ours.
                "evidence_level": "computed",
            }
        )

    if inserts:
        placement_table = sa.table(
            "bgc_organism_placement",
            sa.column("id", sa.Uuid),
            sa.column("bgc_id", sa.Uuid),
            sa.column("representative_genome_id", sa.Uuid),
            sa.column("method", sa.String),
            sa.column("confidence", sa.String),
            sa.column("gtdb_accession", sa.String),
            sa.column("caveat", sa.Text),
            sa.column("created_at", sa.DateTime),
            sa.column("updated_at", sa.DateTime),
            sa.column("source_id", sa.Uuid),
            sa.column("evidence_level", sa.String),
        )
        op.bulk_insert(placement_table, inserts)

    print(
        f"  backfilled {len(inserts)} placement(s) from BGC.raw_annotation"
        + (f"; skipped unknown method(s): {sorted(unknown_methods)}" if unknown_methods else "")
    )


