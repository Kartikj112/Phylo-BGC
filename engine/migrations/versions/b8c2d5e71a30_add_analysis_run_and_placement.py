def _as_uuid(value):
    """Coerce an id read by raw SQL back to a `uuid.UUID`.

    The two dialects disagree and the backfill has to run on both.
    `sqlalchemy.Uuid` stores as native UUID on Postgres (psycopg returns a
    `uuid.UUID`) and as CHAR(32) on SQLite (which returns a plain string).
    Feeding that string back into a `sa.Uuid` bind parameter fails with
    "'str' object has no attribute 'hex'" — found by running this backfill
    against the real 2,437-cluster bundle, not against the empty database
    where there is nothing to insert and the bug cannot appear.
    """
    if value is None or isinstance(value, uuid.UUID):
        return value
    return uuid.UUID(str(value))


