"""Record whether an assembly's two lineages disagree, so a taxid match can be doubted.

Revision ID: e2b6c04f8a13
Revises: c9f1a4d83b57
Create Date: 2026-09-03

Why this exists
---------------
`ingest/link.py` graded an exact NCBI taxid match as STRONG unconditionally:
an identifier had matched an identifier, and that looked like the safest
join available. But the two identifiers do not have the same standing. GTDB
derives an assembly's lineage from the genome itself; the NCBI taxid is
submitter-supplied metadata. When a depositor mislabels an assembly — which
happens most often to metagenome-assembled genomes — an exact taxid match
puts the cluster in the wrong phylum and stamps the result STRONG.

Auditing the shipped corpus against `bac120_metadata` found 73 clusters on
an assembly whose NCBI and GTDB lineages name different phyla. 41 are GTDB
suffix splits (`Myxococcota` vs `Myxococcota_A`) and are not errors at all.
The other **32 are real, all graded STRONG, and all trace to five
assemblies**, four of them MAGs:

    GCA_963591685.1  deposited Escherichia coli    GTDB Actinomycetota   18
    GCA_943323705.2  deposited Streptomyces griseus GTDB Bacteroidota     5
    GCA_943325355.2  deposited Klebsiella pneumoniae GTDB Bacteroidota    5
    GCA_963630775.1  deposited Bacteroides fragilis GTDB Pseudomonadota   3
    GCA_021733645.1  deposited Bacillus subtilis    GTDB Pseudomonadota   1

The last is an isolate, not a MAG, and its own base composition settles it:
67.4% GC, where *B. subtilis* sits near 43.5%.

What the column holds
---------------------
Tri-state, for the same reason `is_mag` was made tri-state one migration
ago (c9f1a4d83b57):

    True   the assembly's NCBI and GTDB lineages name different phyla
    False  they were compared and agree
    NULL   nobody compared them

The backfill, and why it is NULL
--------------------------------
Every existing row becomes NULL, and that is the honest value rather than a
gap. The comparison needs GTDB's `ncbi_taxonomy` column, which lives in the
metadata TSV and not in this database — nothing here can establish the
answer, so nothing here asserts one. Defaulting to False would claim every
assembly had been checked and cleared, which is exactly the failure the
`is_mag` migration removed from a neighbouring column.

Running `bgcscape recheck-placements <bac120_metadata.tsv>` populates the
column from the file the genomes were ingested from and re-grades the
affected placements. Until then a pre-existing database keeps its STRONG
placements, unchanged — this migration deliberately does not silently
re-grade rows on evidence it does not have.

Hand-written, not autogenerated
-------------------------------
Standing rule (ARCHITECTURE.md, "Alembic autogenerate cannot be trusted
with CHECK constraints"). `batch_alter_table` so SQLite, which cannot ALTER
a column in place, can run it.

Downgrade
---------
Drops the column. The placements themselves are left at whatever confidence
they currently hold: a downgrade removes the evidence for the demotion, not
the demotion, and silently promoting 32 known-bad placements back to STRONG
on the way down would be worse than leaving them weak.
"""
from __future__ import annotations

import sqlalchemy as sa
from alembic import op

revision: str = "e2b6c04f8a13"
down_revision: str | None = "c9f1a4d83b57"
branch_labels = None
depends_on = None


def upgrade() -> None:
    with op.batch_alter_table("genome", schema=None) as batch_op:
        batch_op.add_column(
            sa.Column("ncbi_taxonomy_conflict", sa.Boolean(), nullable=True)
        )

    total = op.get_bind().execute(sa.text("SELECT count(*) FROM genome")).scalar() or 0
    strong = (
        op.get_bind()
        .execute(
            sa.text(
                "SELECT count(*) FROM bgc_organism_placement "
                "WHERE confidence = :c AND method IN ('ncbi_taxid', 'ncbi_species_taxid')"
            ),
            {"c": "strong"},
        )
        .scalar()
        or 0
    )
    print(
        f"  ncbi_taxonomy_conflict: added, NULL (unchecked) for all {total} genome(s). "
        f"{strong} identifier-based placement(s) still hold their original confidence — "
        "run `bgcscape recheck-placements <bac120_metadata.tsv>` to check them."
    )


def downgrade() -> None:
    demoted = (
        op.get_bind()
        .execute(
            sa.text(
                "SELECT count(*) FROM bgc_organism_placement "
                "WHERE confidence = :c AND method IN ('ncbi_taxid', 'ncbi_species_taxid')"
            ),
            {"c": "weak"},
        )
        .scalar()
        or 0
    )
    if demoted:
        print(
            f"  NOTE: {demoted} identifier-based placement(s) are recorded weak. They stay "
            "weak; the column recording WHY is going away, so re-run "
            "`recheck-placements` after any future upgrade."
        )
    with op.batch_alter_table("genome", schema=None) as batch_op:
        batch_op.drop_column("ncbi_taxonomy_conflict")
