"""Add the `kingdom` taxonomic rank.

Revision ID: d7e3a91c4f20
Revises: c4a1f7b92e10
Create Date: 2026-08-29

GTDB is prokaryote-only and never emits a kingdom — its ranks run
domain -> phylum -> ... -> species. NCBI ranks eukaryotes with a kingdom in
between (Eukaryota -> Fungi -> Ascomycota), and without it a fungal lineage
cannot be stored at all.

Hand-written, not autogenerated. `TaxonRank` is a CHECK-constrained VARCHAR
(see models/base.py for why `create_constraint=True` matters), so widening
the vocabulary means recreating the constraint. ARCHITECTURE.md's standing
rule applies: autogenerate cannot be trusted with CHECK constraints in this
project, and `include_object` in migrations/env.py now excludes them from
comparison entirely — so this migration is the only place the new value can
enter the database's own guard.

Data-safe in both directions: no existing row uses `kingdom`, so the upgrade
only widens what is permitted. The downgrade narrows it again and will fail
loudly if eukaryote taxa have been ingested, which is the correct behaviour —
silently deleting them would be worse.
"""
from __future__ import annotations

import sqlalchemy as sa
from alembic import op

revision: str = "d7e3a91c4f20"
down_revision: str | None = "c4a1f7b92e10"
branch_labels = None
depends_on = None

_WITH_KINGDOM = (
    "domain",
    "kingdom",
    "phylum",
    "class",
    "order",
    "family",
    "genus",
    "species",
)
_WITHOUT_KINGDOM = tuple(r for r in _WITH_KINGDOM if r != "kingdom")

CONSTRAINT = "ck_taxon_rank_valid"


def _recreate(values: tuple[str, ...]) -> None:
    """Swap the rank CHECK constraint for one over `values`.

    Batch mode so SQLite works: it has no ALTER TABLE DROP CONSTRAINT, so
    Alembic has to recreate the table. Postgres supports the drop directly,
    and batch mode is a no-op shim there.
    """
    allowed = ", ".join(f"'{v}'" for v in values)
    with op.batch_alter_table("taxon", schema=None) as batch_op:
        batch_op.drop_constraint(CONSTRAINT, type_="check")
        batch_op.create_check_constraint(CONSTRAINT, f"rank IN ({allowed})")


def upgrade() -> None:
    _recreate(_WITH_KINGDOM)


def downgrade() -> None:
    remaining = op.get_bind().execute(
        sa.text("SELECT count(*) FROM taxon WHERE rank = 'kingdom'")
    ).scalar()
    if remaining:
        raise RuntimeError(
            f"{remaining} taxa are ranked 'kingdom'. Downgrading would leave rows that "
            "violate the narrowed CHECK constraint. Remove the eukaryote taxonomy first "
            "(e.g. delete the NCBI Taxonomy source's taxa) and re-run."
        )
    _recreate(_WITHOUT_KINGDOM)
