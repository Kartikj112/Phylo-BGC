"""Make `genome.is_mag` tri-state, so "unknown" stops being reported as "no".

Revision ID: c9f1a4d83b57
Revises: b8c2d5e71a30
Create Date: 2026-09-02

Why this exists
---------------
`is_mag` was `NOT NULL DEFAULT False`, and **no ingest path in this project
ever had a source for the value it wrote**:

  * `ingest/gtdb.py` set False with the comment "no verified MAG-detection
    column yet" — an admission in the code that the value was a placeholder;
  * `ingest/mibig.py` set False on a deposited *locus*, which is not an
    assembly at all, so neither answer applies;
  * `ingest/antismash.py` set False from a JSON that carries no assembly
    metadata whatsoever, and said so in a comment naming this exact gap.

The interface read that column and rendered "Isolate genome assembly" for
every one of the 1,542 genomes in the shipped corpus. That is a claim about
each genome's provenance made on no evidence — the same failure the
`AnalysisRun` work removed from cluster counts, in a different column.

`assembly_level` already had `UNKNOWN` for precisely this reason. This gives
`is_mag` the same option.

The backfill, and what it deliberately keeps
--------------------------------------------
Every existing `False` is unverified, so it becomes NULL — with one
exception that is a real signal rather than a default: a row whose
`assembly_level` is already `mag` IS a metagenome-assembled genome, because
that level is parsed from GTDB's own metadata. Those become True.

`True` is left alone everywhere else: nothing writes True by default. It
comes from an operator passing `--is-mag` on an upload, or from the
synthetic demo generator, and in both cases somebody asserted it.

Hand-written, not autogenerated
-------------------------------
Standing rule (ARCHITECTURE.md, "Alembic autogenerate cannot be trusted with
CHECK constraints"). The nullability change is a batch `alter_column` so it
works on SQLite, which cannot ALTER a column in place; the backfill is the
part autogenerate could never produce, and is the part that matters.

Downgrade
---------
Narrowing back to NOT NULL cannot preserve the distinction — there is no
third value to put in a boolean column — so NULLs go back to False, which is
exactly the state this migration exists to correct. That loss is stated here
rather than hidden: downgrading re-asserts "not a MAG" about genomes nothing
has established anything about.
"""
from __future__ import annotations

import sqlalchemy as sa
from alembic import op

revision: str = "c9f1a4d83b57"
down_revision: str | None = "b8c2d5e71a30"
branch_labels = None
depends_on = None


def upgrade() -> None:
    with op.batch_alter_table("genome", schema=None) as batch_op:
        batch_op.alter_column(
            "is_mag",
            existing_type=sa.Boolean(),
            nullable=True,
            existing_server_default=None,
        )

    genome = sa.table(
        "genome",
        sa.column("is_mag", sa.Boolean),
        sa.column("assembly_level", sa.String),
    )

    # Order matters. Promote the rows the assembly level can vouch for
    # BEFORE nulling the rest, or they would be nulled and then no longer
    # match the promotion criterion.
    op.execute(
        genome.update()
        .where(genome.c.assembly_level == "mag")
        .values(is_mag=True)
    )
    result = op.get_bind().execute(
        sa.text("SELECT count(*) FROM genome WHERE is_mag = :f"), {"f": False}
    ).scalar()
    op.execute(genome.update().where(genome.c.is_mag.is_(False)).values(is_mag=None))
    print(
        f"  is_mag: {result or 0} unverified False value(s) -> NULL "
        "(unknown), rows at assembly_level='mag' kept as True"
    )


def downgrade() -> None:
    # No third value survives a NOT NULL boolean. Every "unknown" becomes
    # "not a MAG" again — the claim this migration removed.
    unknown = op.get_bind().execute(
        sa.text("SELECT count(*) FROM genome WHERE is_mag IS NULL")
    ).scalar()
    if unknown:
        print(
            f"  WARNING: {unknown} genome(s) with an UNKNOWN MAG status are being "
            "recorded as 'not a MAG', because a NOT NULL boolean has nowhere else "
            "to put them."
        )
    genome = sa.table("genome", sa.column("is_mag", sa.Boolean))
    op.execute(genome.update().where(genome.c.is_mag.is_(None)).values(is_mag=False))

    with op.batch_alter_table("genome", schema=None) as batch_op:
        batch_op.alter_column(
            "is_mag",
            existing_type=sa.Boolean(),
            nullable=False,
            existing_server_default=None,
        )
